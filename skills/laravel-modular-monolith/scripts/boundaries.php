<?php

declare(strict_types=1);

/**
 * Module boundaries for nwidart/laravel-modules, enforced with Deptrac.
 *
 *   php tools/boundaries.php inspect           read-only state, exit 1 on errors
 *   php tools/boundaries.php sync [--check]    write deptrac.yaml, or fail if it is stale
 *   php tools/boundaries.php selftest          prove the rules fail on planted violations
 *
 * Options: --root <app dir> (default: current directory), --modules <dir> (default: detected).
 * Needs PHP 8.3+. Standard library only; selftest also needs deptrac/deptrac in require-dev.
 */

namespace Boundaries;

const PUBLIC_NAMESPACES = ['Contracts', 'Events'];
const CONFIG_FILE = 'deptrac.yaml';
const HEADER = "# Generated by tools/boundaries.php. Do not edit: change \"boundaries\" in a module.json, then run sync.\n";

final class Module
{
    /**
     * @param  list<string>  $uses  names of modules this one may depend on
     * @param  list<string>  $exposes  extra classes, relative to the module namespace, other modules may use
     */
    public function __construct(
        public readonly string $name,
        public readonly string $namespace,
        public readonly array $uses,
        public readonly array $exposes,
    ) {}
}

final class State
{
    /**
     * @param  array<string, Module>  $modules
     * @param  list<string>  $errors
     */
    public function __construct(
        public readonly string $root,
        public readonly string $modulesDir,
        public readonly array $modules,
        public readonly array $errors,
        public readonly bool $hasHostApp,
    ) {}
}

/** @return array<mixed> */
function readJson(string $path): array
{
    $text = @file_get_contents($path);
    if ($text === false) {
        return [];
    }
    $data = json_decode($text, true);

    return is_array($data) ? $data : [];
}

/** @param array<mixed> $data */
function dig(array $data, string ...$keys): mixed
{
    $value = $data;
    foreach ($keys as $key) {
        if (! is_array($value) || ! array_key_exists($key, $value)) {
            return null;
        }
        $value = $value[$key];
    }

    return $value;
}

function modulesDir(string $root, ?string $flag): string
{
    if ($flag !== null) {
        return trim(str_replace('\\', '/', $flag), '/');
    }
    $include = dig(readJson("$root/composer.json"), 'extra', 'merge-plugin', 'include');
    foreach (is_array($include) ? $include : [] as $pattern) {
        if (is_string($pattern) && preg_match('#^(.+)/\*/composer\.json$#', $pattern, $match) === 1) {
            return trim($match[1], './');
        }
    }

    return 'Modules';
}

function moduleNamespace(string $dir, string $name): string
{
    $autoload = dig(readJson("$dir/composer.json"), 'autoload', 'psr-4');
    $candidates = array_values(array_filter(array_keys(is_array($autoload) ? $autoload : []), 'is_string'));
    usort($candidates, static fn (string $a, string $b): int => strlen($a) <=> strlen($b));

    return rtrim($candidates[0] ?? "Modules\\$name", '\\').'\\';
}

/** @return list<string> */
function stringList(mixed $value): array
{
    return array_values(array_filter((array) $value, 'is_string'));
}

function discover(string $root, ?string $modulesFlag): State
{
    $modulesDir = modulesDir($root, $modulesFlag);
    $errors = [];
    $modules = [];
    if (! is_file("$root/artisan")) {
        $errors[] = "no artisan file in $root: run from the Laravel app root or pass --root";
    }
    $manifests = glob("$root/$modulesDir/*/module.json") ?: [];
    sort($manifests);
    foreach ($manifests as $manifest) {
        $dir = dirname($manifest);
        $json = readJson($manifest);
        $name = is_string($json['name'] ?? null) ? $json['name'] : basename($dir);
        $boundaries = is_array($json['boundaries'] ?? null) ? $json['boundaries'] : [];
        $modules[$name] = new Module(
            $name,
            moduleNamespace($dir, $name),
            stringList($boundaries['uses'] ?? []),
            array_map(static fn (string $class): string => trim($class, '\\'), stringList($boundaries['exposes'] ?? [])),
        );
    }
    foreach ($modules as $module) {
        foreach ($module->uses as $used) {
            if ($used === $module->name) {
                $errors[] = "$module->name: lists itself in boundaries.uses";
            } elseif (! isset($modules[$used])) {
                $errors[] = "$module->name: boundaries.uses names unknown module $used";
            }
        }
    }
    foreach (cycles($modules) as $cycle) {
        $errors[] = 'cycle: '.implode(' -> ', $cycle);
    }

    return new State($root, $modulesDir, $modules, $errors, is_dir("$root/app"));
}

/**
 * @param  array<string, Module>  $modules
 * @return list<list<string>>
 */
function cycles(array $modules): array
{
    $found = [];
    $done = [];
    foreach (array_keys($modules) as $name) {
        $found = [...$found, ...cyclesFrom($name, [], $modules, $done)];
    }

    return $found;
}

/**
 * @param  list<string>  $path
 * @param  array<string, Module>  $modules
 * @param  array<string, true>  $done
 * @return list<list<string>>
 */
function cyclesFrom(string $name, array $path, array $modules, array &$done): array
{
    $at = array_search($name, $path, true);
    if ($at !== false) {
        return [[...array_slice($path, $at), $name]];
    }
    if (isset($done[$name]) || ! isset($modules[$name])) {
        return [];
    }
    $found = [];
    foreach ($modules[$name]->uses as $used) {
        $found = [...$found, ...cyclesFrom($used, [...$path, $name], $modules, $done)];
    }
    $done[$name] = true;

    return $found;
}

function quote(string $namespaceOrClass): string
{
    return preg_quote($namespaceOrClass, '/');
}

function exposedPattern(Module $module): string
{
    return implode('|', array_map(quote(...), $module->exposes));
}

/** @return array<string, string> layer name => class regex */
function layers(State $state): array
{
    $layers = [];
    $public = implode('|', PUBLIC_NAMESPACES);
    foreach ($state->modules as $module) {
        $ns = quote($module->namespace);
        $notExposed = $module->exposes === [] ? '' : '(?!(?:'.exposedPattern($module).')$)';
        $layers[$module->name] = "^{$ns}(?!(?:$public)\\\\){$notExposed}.+";
        $layers["$module->name.Public"] = "^{$ns}(?:$public)\\\\.+";
        if ($module->exposes !== []) {
            $layers["$module->name.Exposed"] = "^{$ns}(?:".exposedPattern($module).')$';
        }
    }
    if ($state->hasHostApp) {
        $layers['App'] = '^App\\\\.+';
    }

    return $layers;
}

/** @return list<string> the layers of a module that other code may use */
function surface(Module $module): array
{
    return $module->exposes === [] ? ["$module->name.Public"] : ["$module->name.Public", "$module->name.Exposed"];
}

/** @return array<string, list<string>> layer name => layers it may depend on */
function ruleset(State $state): array
{
    $rules = [];
    $host = $state->hasHostApp ? ['App'] : [];
    foreach ($state->modules as $module) {
        $used = [];
        $usedPublic = [];
        foreach ($module->uses as $name) {
            if (isset($state->modules[$name])) {
                $used = [...$used, ...surface($state->modules[$name])];
                $usedPublic[] = "$name.Public";
            }
        }
        $rules[$module->name] = [...surface($module), ...$used, ...$host];
        $rules["$module->name.Public"] = $usedPublic;
        if ($module->exposes !== []) {
            $rules["$module->name.Exposed"] = [$module->name, "$module->name.Public", ...$used, ...$host];
        }
    }
    if ($state->hasHostApp) {
        $rules['App'] = array_merge(...array_map(surface(...), array_values($state->modules)));
    }

    return $rules;
}

/** @param list<string> $paths */
function render(State $state, array $paths): string
{
    $yaml = HEADER."deptrac:\n  paths:\n";
    foreach ($paths as $path) {
        $yaml .= "    - '$path'\n";
    }
    $yaml .= "  exclude_files:\n    - '#[/\\\\]tests[/\\\\]#'\n  layers:\n";
    foreach (layers($state) as $name => $pattern) {
        $yaml .= "    - name: $name\n      collectors:\n        - type: classLike\n          value: '".str_replace("'", "''", $pattern)."'\n";
    }
    $yaml .= "  ruleset:\n";
    foreach (ruleset($state) as $name => $allowed) {
        $yaml .= $allowed === [] ? "    $name: ~\n" : "    $name:\n".implode('', array_map(static fn (string $layer): string => "      - $layer\n", $allowed));
    }

    return $yaml;
}

function expected(State $state): string
{
    $paths = ["./$state->modulesDir"];
    if ($state->hasHostApp) {
        $paths[] = './app';
    }

    return render($state, $paths);
}

function inSync(State $state): bool
{
    $current = @file_get_contents("$state->root/".CONFIG_FILE);

    return $current !== false && str_replace("\r\n", "\n", $current) === expected($state);
}

function deptrac(State $state): ?string
{
    $path = "$state->root/vendor/bin/deptrac";

    return is_file($path) ? $path : null;
}

function inspect(State $state): int
{
    echo "root: $state->root\nmodules dir: $state->modulesDir\nmodules: ".count($state->modules)."\n";
    foreach ($state->modules as $module) {
        echo "  $module->name ($module->namespace) uses: ".(implode(', ', $module->uses) ?: 'none')
            .($module->exposes === [] ? '' : '; exposes: '.implode(', ', $module->exposes))."\n";
    }
    echo 'deptrac: '.(deptrac($state) === null ? 'missing (composer require --dev deptrac/deptrac)' : 'installed')."\n";
    echo CONFIG_FILE.': '.(is_file("$state->root/".CONFIG_FILE) ? (inSync($state) ? 'in sync' : 'stale, run sync') : 'missing, run sync')."\n";
    foreach ($state->errors as $error) {
        fwrite(STDERR, "error: $error\n");
    }

    return $state->errors === [] ? 0 : 1;
}

function sync(State $state, bool $check): int
{
    if ($state->errors !== []) {
        return inspect($state);
    }
    if ($check) {
        if (inSync($state)) {
            echo 'ok: '.CONFIG_FILE." is in sync\n";

            return 0;
        }
        fwrite(STDERR, 'error: '.CONFIG_FILE." is stale or missing, run: php tools/boundaries.php sync\n");

        return 1;
    }
    file_put_contents("$state->root/".CONFIG_FILE, expected($state));
    echo 'wrote '.CONFIG_FILE.' for '.count($state->modules)." modules\n";

    return 0;
}

/**
 * One planted class per rule: [class name, the class it depends on, whether Deptrac must report it].
 *
 * @return list<array{string, string, bool}>
 */
function cases(State $state): array
{
    $cases = [];
    $add = static function (string $namespace, string $target, bool $violation) use (&$cases): void {
        $cases[] = [$namespace.'SelftestCase'.count($cases), $target, $violation];
    };
    foreach ($state->modules as $module) {
        $internal = $module->namespace.'Services\\';
        $add($module->namespace.'Contracts\\', $module->namespace.'Services\\SelftestTarget', true);
        $add($internal, $module->namespace.'Contracts\\SelftestTarget', false);
        foreach ($state->modules as $other) {
            if ($other->name === $module->name) {
                continue;
            }
            $add($internal, $other->namespace.'Services\\SelftestTarget', true);
            $add($internal, $other->namespace.'Contracts\\SelftestTarget', ! in_array($other->name, $module->uses, true));
            foreach ($other->exposes as $class) {
                $add($internal, $other->namespace.$class, ! in_array($other->name, $module->uses, true));
            }
        }
        if ($state->hasHostApp) {
            $add('App\\Selftest\\', $module->namespace.'Services\\SelftestTarget', true);
            $add('App\\Selftest\\', $module->namespace.'Contracts\\SelftestTarget', false);
        }
    }

    return $cases;
}

function classFile(string $class, ?string $dependsOn): string
{
    $at = (int) strrpos($class, '\\');
    $body = $dependsOn === null ? '' : " public function run(\\$dependsOn \$target): void {} ";

    return "<?php\n\nnamespace ".substr($class, 0, $at).";\n\nfinal class ".substr($class, $at + 1)." {{$body}}\n";
}

function removeTree(string $dir): void
{
    foreach (scandir($dir) ?: [] as $entry) {
        if ($entry !== '.' && $entry !== '..') {
            is_dir("$dir/$entry") ? removeTree("$dir/$entry") : @unlink("$dir/$entry");
        }
    }
    @rmdir($dir);
}

function selftest(State $state): int
{
    if ($state->errors !== []) {
        return inspect($state);
    }
    $deptrac = deptrac($state);
    if ($deptrac === null) {
        fwrite(STDERR, "error: deptrac is missing, run: composer require --dev deptrac/deptrac\n");

        return 1;
    }
    if ($state->modules === []) {
        fwrite(STDERR, "error: no modules found in $state->modulesDir\n");

        return 1;
    }
    $dir = sys_get_temp_dir().'/boundaries-selftest-'.bin2hex(random_bytes(4));
    mkdir("$dir/src", 0777, true);
    try {
        $cases = cases($state);
        $classes = [];
        foreach ($cases as [$class, $target]) {
            $classes[$class] = $target;
            $classes[$target] ??= null;
        }
        $number = 0;
        foreach ($classes as $class => $target) {
            file_put_contents("$dir/src/".$number++.'.php', classFile($class, $target));
        }
        file_put_contents("$dir/deptrac.yaml", render($state, ['./src']));
        $command = [PHP_BINARY, $deptrac, 'analyse', "--config-file=$dir/deptrac.yaml", '--formatter=json', "--output=$dir/report.json", '--no-cache', '--no-progress', '--no-interaction'];
        $process = proc_open($command, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, $dir);
        if (! is_resource($process)) {
            fwrite(STDERR, "error: could not start deptrac\n");

            return 1;
        }
        $output = stream_get_contents($pipes[1]).stream_get_contents($pipes[2]);
        proc_close($process);
        $report = readJson("$dir/report.json");
        if (! isset($report['Report'])) {
            fwrite(STDERR, "error: deptrac gave no report\n$output\n");

            return 1;
        }
        $reported = [];
        $files = dig($report, 'files');
        foreach (is_array($files) ? $files : [] as $file) {
            $messages = is_array($file) ? ($file['messages'] ?? null) : null;
            foreach (is_array($messages) ? $messages : [] as $message) {
                $text = is_array($message) && ($message['type'] ?? null) === 'error' ? ($message['message'] ?? null) : null;
                if (is_string($text) && preg_match('/^(\S+) must not depend on/', $text, $match) === 1) {
                    $reported[$match[1]] = true;
                }
            }
        }
        $failures = [];
        foreach ($cases as [$class, $target, $violation]) {
            if ($violation !== isset($reported[$class])) {
                $failures[] = ($violation ? 'not caught' : 'wrongly reported').": $class -> $target";
            }
        }
        foreach ($failures as $failure) {
            fwrite(STDERR, "error: $failure\n");
        }
        if ($failures !== []) {
            return 1;
        }
        $caught = count(array_filter($cases, static fn (array $case): bool => $case[2]));
        echo "ok: $caught planted violations caught, ".(count($cases) - $caught)." allowed dependencies passed\n";

        return 0;
    } finally {
        removeTree($dir);
    }
}

/** @param list<string> $argv */
function main(array $argv): int
{
    $command = null;
    $options = ['--root' => null, '--modules' => null];
    $check = false;
    for ($i = 1; $i < count($argv); $i++) {
        $arg = $argv[$i];
        if (array_key_exists($arg, $options) && isset($argv[$i + 1])) {
            $options[$arg] = $argv[++$i];
        } elseif ($arg === '--check') {
            $check = true;
        } elseif ($command === null && ! str_starts_with($arg, '-')) {
            $command = $arg;
        } else {
            $command = 'help';
        }
    }
    $root = realpath($options['--root'] ?? (string) getcwd());
    if ($root === false) {
        fwrite(STDERR, "error: --root does not exist\n");

        return 1;
    }
    $state = discover(str_replace('\\', '/', $root), $options['--modules']);

    return match ($command) {
        'inspect' => inspect($state),
        'sync' => sync($state, $check),
        'selftest' => selftest($state),
        default => (static function (): int {
            fwrite(STDERR, "usage: php tools/boundaries.php inspect|sync [--check]|selftest [--root <dir>] [--modules <dir>]\n");

            return 2;
        })(),
    };
}

$script = $_SERVER['SCRIPT_FILENAME'] ?? null;
if (PHP_SAPI === 'cli' && is_string($script) && realpath($script) === __FILE__) {
    $arguments = $_SERVER['argv'] ?? null;
    exit(main(array_values(array_filter(is_array($arguments) ? $arguments : [], 'is_string'))));
}
